// Converts drizzle/migrations/*/migration.sql files into a TypeScript
// manifest that can be imported by drizzle-orm/durable-sqlite/migrator.
// Run after drizzle-kit generate: node scripts/build-migration-manifest.mjs
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const MIGRATIONS_DIR = new URL("../drizzle/migrations/", import.meta.url);
const OUT_FILE = new URL("../drizzle/migrations/index.ts", import.meta.url);

async function main() {
  const entries = await readdir(MIGRATIONS_DIR, { withFileTypes: true });
  const dirs = entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  /** @type {Record<string, string>} */
  const migrations = {};
  for (const dir of dirs) {
    const sqlPath = path.join(MIGRATIONS_DIR.pathname, dir, "migration.sql");
    const sql = await readFile(sqlPath, "utf8");
    migrations[dir] = sql;
  }

  const lines = [
    "// Auto-generated by scripts/build-migration-manifest.ts",
    "// Do not edit by hand. Regenerate after `drizzle-kit generate`.",
    "",
    "export default {",
  ];
  for (const [name, sql] of Object.entries(migrations)) {
    lines.push(`  "${name}": ${JSON.stringify(sql)},`);
  }
  lines.push("} as const;");
  lines.push("");

  await writeFile(OUT_FILE, lines.join("\n"), "utf8");
  console.log(`Wrote ${Object.keys(migrations).length} migration(s) to ${OUT_FILE.pathname}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
